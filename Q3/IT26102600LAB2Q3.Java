public class Main {
    public static void main(String[] args) {

        double sideA = 3;
        double sideB = 4;

        // Calculate the hypotenuse
        double hypotenuse = Math.sqrt((sideA * sideA) + (sideB * sideB));

        System.out.println("Hypotenuse = " + hypotenuse);
    }
}