public class IT26102526Lab2Q3{
	public static void main(String[] args) {
			int sideA = 3;
			int sideB = 4;
			
			double length_hypotenuse;
			
			length_hypotenuse = Math.sqrt((sideA * sideA) + (sideB * sideB));
			
			System.out.println("Length of the hypotenuse: " + length_hypotenuse);
			
	}
	
}